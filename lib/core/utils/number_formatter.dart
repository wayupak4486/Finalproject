// ==============================================================================
// ส่วนที่ 1: นำเข้าแพ็กเกจ (Import)
// ==============================================================================
// นำเข้าแพ็กเกจ 'intl' เพื่อใช้คลาส NumberFormat (จัดการลูกน้ำและทศนิยม)
import 'package:intl/intl.dart'; //

// ==============================================================================
// ส่วนที่ 2: คลาส NumberFormatter
// ==============================================================================
class NumberFormatter {
  // ล็อคไม่ให้สร้างออบเจกต์ (ป้องกันการใช้คำสั่ง NumberFormatter() ให้เรียกใช้ฟังก์ชันตรงๆ)
  const NumberFormatter._(); //

  // ----------------------------------------------------------------------------
  // ฟังก์ชันที่ 1: money (แปลงตัวเลขเป็นข้อความจำนวนเงิน)
  // ----------------------------------------------------------------------------
  static String money(double value) {
    //
    // โครงสร้าง '#,##0.00' หมายถึง:
    // #,##0 = ให้ใส่ลูกน้ำคั่นหลักพันเสมอ (เช่น 1,250)
    // .00   = บังคับให้แสดงทศนิยม 2 ตำแหน่งเสมอ (เช่น 10 จะกลายเป็น 10.00)
    // ${...} เป็นการทำ String Interpolation เพื่อนำผลลัพธ์มาต่อกับคำว่า ' บาท'
    return '${NumberFormat('#,##0.00').format(value)} บาท'; //
  }

  // ----------------------------------------------------------------------------
  // ฟังก์ชันที่ 2: kg (แปลงตัวเลขเป็นข้อความน้ำหนัก)
  // ----------------------------------------------------------------------------
  static String kg(double value) {
    //
    // โครงสร้าง '#,##0.##' หมายถึง:
    // .## = ให้แสดงทศนิยมสูงสุด 2 ตำแหน่ง แต่! ถ้าเป็นเลขลงตัว (เศษเป็น 0) ให้ซ่อนทศนิยมไปเลย
    // (เช่น 1.50 จะแสดงเป็น 1.5 / 10.00 จะแสดงเป็น 10 ถ้วนๆ)
    return '${NumberFormat('#,##0.##').format(value)} กก.'; //
  }

  // ----------------------------------------------------------------------------
  // ฟังก์ชันที่ 3: co2 (แปลงตัวเลขเป็นปริมาณคาร์บอน)
  // ----------------------------------------------------------------------------
  static String co2(double value) {
    //[cite: 15]
    // โครงสร้างเหมือนน้ำหนัก (แสดงทศนิยมไม่เกิน 2 ตำแหน่งและซ่อนศูนย์ต่อท้าย)
    return '${NumberFormat('#,##0.##').format(value)} กก.CO₂e'; //[cite: 15]
  }

  // ----------------------------------------------------------------------------
  // ฟังก์ชันที่ 4: percent (แปลงตัวเลขสัดส่วนให้เป็นเปอร์เซ็นต์)
  // ----------------------------------------------------------------------------
  static String percent(double value) {
    //[cite: 15]
    // เอา value * 100 ก่อน (เช่น 0.85 * 100 = 85)
    // โครงสร้าง '0.0' = บังคับให้มีทศนิยม 1 ตำแหน่งเสมอ (เช่น 85.0%)
    return '${NumberFormat('0.0').format(value * 100)}%'; //[cite: 15]
  }
}
