  // กลุ่มที่ 3: สีตัวอักษร (Typography Colors)
  // ----------------------------------------------------------------------------
  static const Color textDark = Color(0xFF1E211D);             // สีข้อความหลัก (เกือบดำ)
  static const Color textMuted = Color(0xFF5E665B);            // สีข้อความรอง (เทาอมเขียว)
