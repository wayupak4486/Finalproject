// ===========================================================================
// การสร้างคลาส (Class) เพื่อเป็น "แม่พิมพ์" สำหรับกล่องเก็บผลลัพธ์ AI
// ===========================================================================
class ClassificationResult {
  
  // 💡 Constructor: ฟังก์ชันสำหรับ "สร้างกล่อง" และ "รับของใส่กล่อง"
  // คำว่า const ด้านหน้าหมายถึง ถ้าสร้างกล่องนี้ด้วยข้อมูลชุดเดิมเป๊ะๆ 
  // ระบบจะใช้กล่องเดิมใน RAM โดยไม่สร้างใหม่ (ช่วยประหยัดหน่วยความจำมือถือ)
  const ClassificationResult({
    
    // required แปลว่า "บังคับต้องใส่ข้อมูลนี้มาด้วย ห้ามปล่อยว่าง (ห้ามเป็น null)"
    // this.label หมายถึง เอาข้อมูลที่รับมา ไปยัดใส่ตัวแปร label ด้านล่างทันที
    required this.label, 
    required this.confidence, 
    required this.allScores, 
  });

  // ===========================================================================
  // โซนประกาศตัวแปร (ของที่อยู่ในกล่อง)
  // คำว่า 'final' แปลว่า "กำหนดค่าได้แค่ครั้งเดียวตอนสร้างกล่อง หลังจากนั้นห้ามแก้ไขเด็ดขาด!"
  // ===========================================================================

  // ตัวแปรเก็บชื่อคลาสที่ AI ทายมา (เช่น 'ขวดพลาสติก')
  final String label; 
  
  // ตัวแปรเก็บคะแนนความมั่นใจของตัวที่ชนะ (ตั้งแต่ 0.0 - 1.0)
  final double confidence; 
  
  // ตัวแปรเก็บตารางคะแนนของขยะทุกชนิด (Map คือโครงสร้างข้อมูลแบบ Key-Value)
  // Key เป็น String (ชื่อขยะ) และ Value เป็น double (คะแนนความมั่นใจ)
  final Map<String, double> allScores; 
}