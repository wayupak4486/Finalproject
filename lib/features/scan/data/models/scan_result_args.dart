// 💡 import: คือการดึงโครงสร้างของ "ผลลัพธ์ AI" (ClassificationResult) มาจากโฟลเดอร์ services
// เพื่อให้ไฟล์นี้รู้ว่า ClassificationResult หน้าตาเป็นยังไง
import '../../../../services/ml/classification_result.dart';

// ===========================================================================
// สร้างคลาสชื่อ ScanResultArgs (ย่อมาจาก Arguments)
// ทำหน้าที่เป็น "กล่องพัสดุ" สำหรับบรรจุข้อมูลส่งข้ามหน้าจอ
// ===========================================================================
class ScanResultArgs {
  // 💡 Constructor: ฟังก์ชันสร้างกล่องพัสดุ (ชื่อต้องตรงกับชื่อคลาสเป๊ะๆ)
  // - const = ยืนยันว่าเมื่อสร้างกล่องนี้ขึ้นมาแล้ว โครงสร้างจะไม่เปลี่ยนไปเปลี่ยนมา ประหยัดแรมแอป
  // - ปีกกา { ... } = Named Parameters: บังคับว่าเวลาเรียกใช้ ต้องระบุชื่อตัวแปรด้วย (เช่น imagePath: '...', result: '...') เพื่อกันการส่งค่าผิดสลับตำแหน่งกัน
  // - required = บังคับว่าตอนสร้างกล่องนี้ "ห้ามลืม" ส่ง 2 ค่านี้มาเด็ดขาด (ถึงแม้ imagePath จะอนุญาตให้ส่งค่า null เข้ามาได้ แต่มันบังคับว่าต้องพิมพ์คำว่า imagePath: null ห้ามเว้นว่างไปเฉยๆ)
  const ScanResultArgs({required this.imagePath, required this.result});

  // 💡 ตัวแปรที่ 1: เก็บที่อยู่ของรูปภาพ (เช่น '/data/user/0/com.app/image.jpg')
  // - final = เมื่อรับค่ารูปภาพเข้ามาแล้ว "ห้ามแก้ไข" ระหว่างทางเด็ดขาด ป้องกันข้อมูลเพี้ยน
  // - String? = สำคัญมาก! เครื่องหมาย ? คือ "Nullable" แปลว่า "กล่องนี้สามารถไม่มีรูป (เป็น null) ก็ได้"
  // (แก้ปัญหาแอปพัง (Crash) ในกรณีที่ผู้ใช้ "เลือกวัสดุเอง" แทนการใช้กล้องถ่ายรูป)
  final String? imagePath;

  // 💡 ตัวแปรที่ 2: เก็บผลลัพธ์ AI
  // - final = ห้ามแก้ไขข้อมูลผลลัพธ์ระหว่างทาง
  // - ClassificationResult = ไม่ใส่ ? หมายความว่า "ยังไงซะก็ต้องมีผลลัพธ์ (ห้ามเป็น null)"
  // (ไม่ว่า AI จะคิดให้ หรือผู้ใช้จะจิ้มเลือกเอง ก็ต้องมีผลลัพธ์แนบมาเสมอ)
  final ClassificationResult result;
}
