// ==============================================================================
// ส่วนที่ 1: นำเข้าไฟล์ (Import) ที่จำเป็น
// ==============================================================================
import 'package:flutter/material.dart'; // นำเข้าเครื่องมือสร้าง UI สีและสไตล์ต่างๆ ของ Flutter

// ==============================================================================
// ส่วนที่ 2: คลาส AppTheme สำหรับคุมสไตล์ทั้งแอป
// ==============================================================================
class AppTheme {
  // ----------------------------------------------------------------------------
  // Private Constructor: ล็อคไม่ให้สร้างออบเจกต์ด้วยคำสั่ง AppTheme()
  // (อธิบายเหมือนไฟล์ router.dart เป๊ะครับ เป็นเทคนิคจัดการหน่วยความจำ)
  // ----------------------------------------------------------------------------
  const AppTheme._();

  // ----------------------------------------------------------------------------
  // ส่วนที่ 3: กำหนด "แม่สีหลัก" ของแอปพลิเคชัน (Seed Color)
  // รหัสสี 0xFF นำหน้าหมายถึง ความโปร่งใส 100% (ทึบแสง) ตามด้วยรหัสสี Hex: 2E7D32 (สีเขียวเข้ม)
  // ----------------------------------------------------------------------------
  static const Color seedColor = Color(0xFF2E7D32);

  // ----------------------------------------------------------------------------
  // ส่วนที่ 4: ฟังก์ชัน lightTheme สำหรับสร้างชุดธีมสว่าง
  // ฟังก์ชันแบบ Getter คืนค่าเป็น ThemeData
  // ----------------------------------------------------------------------------
  static ThemeData get lightTheme {
    // 4.1 สร้างชุดสี (ColorScheme) อัตโนมัติจากแม่สี (seedColor)
    // ระบบจะเอาสีเขียวไปสร้างสีเขียวอ่อน สีพื้นหลัง สีกระทบแสง ฯลฯ ให้เองแบบเนียนๆ
    final colorScheme = ColorScheme.fromSeed(
      seedColor: seedColor, // โยนแม่สีเข้าไป
      brightness:
          Brightness.light, // ระบุว่าเป็นธีมสว่าง (พื้นขาว ตัวหนังสือดำ)
    );

    // 4.2 สร้างและส่งคืนข้อมูลธีมทั้งหมด (ThemeData) เพื่อเอาไปใช้ครอบทั้งแอป
    return ThemeData(
      // เปิดใช้งานดีไซน์ Material 3 (ดีไซน์ยุคใหม่ของแอนดรอยด์)
      useMaterial3: true,

      // ยัดชุดสีที่เจเนอเรตเสร็จแล้วในข้อ 4.1 เข้าไป
      colorScheme: colorScheme,

      // ตั้งสีพื้นหลังของทุกหน้าจอ ให้ใช้สี surface จากชุดสี (มักจะเป็นสีขาวหรือเทาอ่อนมากๆ)
      scaffoldBackgroundColor: colorScheme.surface,

      // ------------------------------------------------------------------------
      // 4.3 ตั้งค่าหน้าตาของ แถบนำทางด้านบน (AppBar) สำหรับทุกหน้าจอ
      // ------------------------------------------------------------------------
      appBarTheme: AppBarTheme(
        centerTitle: true, // ให้ข้อความชื่อหน้าจออยู่ตรงกลางเสมอ
        backgroundColor:
            colorScheme.surface, // สีพื้นหลัง AppBar กลืนไปกับสีพื้นหลังจอ
        foregroundColor: colorScheme
            .onSurface, // สีตัวหนังสือบน AppBar (มักจะเป็นสีดำ/เทาเข้ม)
        elevation: 0, // เงาใต้ AppBar ตั้งเป็น 0 คือไม่มีเงา (ดีไซน์แบบแบนราบ)
      ),

      // ------------------------------------------------------------------------
      // 4.4 ตั้งค่าหน้าตาของ การ์ด (Card) สำหรับกล่องใส่ข้อมูลต่างๆ
      // ------------------------------------------------------------------------
      cardTheme: CardThemeData(
        elevation: 0, // ไม่มีเงาใต้การ์ด
        color: colorScheme
            .surfaceContainerHighest, // สีพื้นหลังการ์ด (จะเป็นสีทึบกว่าพื้นหลังจอเล็กน้อย)
        // ทำมุมการ์ดให้โค้งมน 20 พิกเซล
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
      ),

      // ------------------------------------------------------------------------
      // 4.5 ตั้งค่าหน้าตาของ ปุ่มกดหลัก (FilledButton)
      // ------------------------------------------------------------------------
      filledButtonTheme: FilledButtonThemeData(
        style: FilledButton.styleFrom(
          minimumSize: const Size.fromHeight(
            52,
          ), // ตั้งความสูงปุ่มขั้นต่ำ 52 พิกเซล (และกว้างเต็มจอ)
          // ทำมุมปุ่มให้โค้งมน 16 พิกเซล
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(16),
          ),
        ),
      ),
    );
  }
}
