// ==============================================================================
// ส่วนที่ 1: นำเข้าไฟล์ (Import) ที่จำเป็นต้องใช้งาน
// ==============================================================================
import 'package:flutter/material.dart'; // นำเข้าเครื่องมือหลักของ Flutter สำหรับสร้างหน้าตาแอป (Material Design)
import 'router.dart'; // นำเข้าไฟล์ router.dart (ใช้ดึงรายชื่อหน้าจอต่างๆ มาผูกกับแอป)
import 'theme.dart'; // นำเข้าไฟล์ theme.dart (ใช้ดึงการตั้งค่าสีและฟอนต์มาตกแต่งแอป)

// ==============================================================================
// ส่วนที่ 2: คลาสหลักของแอปพลิเคชัน (จุดเริ่มต้นของ UI)
// ==============================================================================
// สร้างคลาสชื่อ RecycleAiApp โดยสืบทอดมาจาก StatelessWidget (หมายถึงหน้านี้จะไม่มีการเปลี่ยนแปลงข้อมูลหรือ State ใดๆ)
class RecycleAiApp extends StatelessWidget {
  // Constructor (ตัวสร้างคลาส) รับคีย์มาเพื่อระบุตัวตนของวิดเจ็ตนี้ในระบบ
  const RecycleAiApp({super.key});

  // ----------------------------------------------------------------------------
  // ฟังก์ชัน build: ทำหน้าที่สร้างและคืนค่าหน้าตาของแอปพลิเคชัน (โดนเรียกอัตโนมัติเมื่อแอปเริ่ม)
  // ----------------------------------------------------------------------------
  @override
  Widget build(BuildContext context) {
    // คืนค่าโครงสร้างแอปพลิเคชันแบบ Material Design (แอปแอนดรอยด์/iOS มาตรฐาน)
    return MaterialApp(
      // 1. ตั้งชื่อแอปพลิเคชัน (จะแสดงเวลาผู้ใช้กดดู Recent Apps หรือ Task Switcher บนมือถือ)
      title: 'แชะแล้วรู้',

      // 2. ปิดป้ายคาดมุมขวาบนที่เขียนว่า "DEBUG" (ตั้งเป็น false คือไม่แสดง)
      debugShowCheckedModeBanner: false,

      // 3. ตั้งค่าธีมของแอปพลิเคชัน โดยไปดึงค่า 'lightTheme' ที่ตั้งไว้ในไฟล์ theme.dart มาใช้
      theme: AppTheme.lightTheme,

      // 4. กำหนดหน้าแรกที่แอปจะเปิดขึ้นมา โดยไปดึงตัวแปร 'home' จากไฟล์ router.dart (AppRoutes)
      initialRoute: AppRoutes.home,

      // 5. ลงทะเบียนเส้นทาง (หน้าจอ) ทั้งหมดในแอป เพื่อให้สามารถกดเปลี่ยนหน้าจอไปมาได้
      routes: AppRoutes.routes,
    ); // จบการตั้งค่า MaterialApp
  } // จบฟังก์ชัน build
} // จบคลาส RecycleAiApp
